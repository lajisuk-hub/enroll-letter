// AI를 쓸 수 없을 때 쓰는 기본 편지
export function fallbackLetter(d) {
  const first = [d.firstTags?.[0], d.firstDay].filter(Boolean).join(' ');
  const grow = [...(d.growTags || []).slice(0, 2), d.grow].filter(Boolean).join(', ');
  return [
    `사랑하는 ${d.child} 어머님, 아버님께`,
    `2026년 봄, ${d.child}를 처음 만나던 날이 아직도 선명합니다.${first ? ` ${first.replace(/요$/, '던')} 그 작은 모습을 보며, 이 아이와 함께할 한 해가 참 기대되었습니다.` : ' 낯선 교실에 들어서던 작은 발걸음을 보며, 이 아이와 함께할 한 해가 참 기대되었습니다.'}`,
    `계절이 몇 번 바뀌는 동안 ${d.child}는 하루하루 조금씩 자랐습니다.${grow ? ` 이제는 ${grow}.` : ''} 그 모든 순간을 곁에서 지켜볼 수 있어서 선생님들은 정말 행복했습니다.`,
    d.moment ? `특히 ${d.moment} 그 장면은 오래도록 마음에 남을 것 같습니다.` : '',
    d.toChild ? `${d.child}에게 이렇게 말해 주고 싶습니다. ${d.toChild}` : `${d.child}야, 한 해 동안 정말 멋지게 자라 주어서 고마워.`,
    `${d.toParent ? d.toParent + ' ' : ''}2027년에도 ${d.child}의 다음 성장을 가장 가까이에서 함께하고 싶습니다. 늘 믿고 맡겨 주셔서 진심으로 감사드립니다.`,
    `${d.center} 원장 ${d.director} 드림`,
  ].filter(Boolean).join('\n\n');
}
